import type { Project, StatusConfig, Task } from '../types'
import { isTerminalStatus, sanitizeFileName } from '../utils'
import { appendYaml, FRONTMATTER_KEY, stripAutoGeneratedContent, TASK_FRONTMATTER_KEY } from './YamlParser'

// ─── Serialize ──────────────────────────────────────────────────────────────

export function serializeProject(project: Project, statuses: StatusConfig[] = []): string {
  const seen = new Set<string>()
  const tasks: Task[] = []
  for (const t of project.tasks) {
    if (seen.has(t.id)) continue
    seen.add(t.id)
    tasks.push(t)
  }
  const taskIds = tasks.map((t) => t.id)

  const fm: Record<string, unknown> = {
    [FRONTMATTER_KEY]: true,
    id: project.id,
    title: project.title,
    description: project.description,
    color: project.color,
    icon: project.icon,
    taskIds,
    customFields: project.customFields,
    teamMembers: project.teamMembers,
    savedViews: project.savedViews.length ? project.savedViews : [],
    createdAt: project.createdAt,
    updatedAt: project.updatedAt
  }
  // Connector data lives in a single namespaced `ext` block (e.g. ext.jira).
  if (project.ext) fm.ext = project.ext

  const yamlLines: string[] = ['---']
  appendYaml(yamlLines, fm, 0)
  yamlLines.push('---')
  yamlLines.push('')
  yamlLines.push(`# ${project.icon} ${project.title}`)
  yamlLines.push('')
  if (project.description) {
    yamlLines.push(project.description)
    yamlLines.push('')
  }
  if (tasks.length) {
    yamlLines.push('## Tasks')
    for (const t of tasks) {
      if (t.filePath) {
        const basename = t.filePath.replace(/^.*\//, '').replace(/\.md$/, '')
        const check = isTerminalStatus(t.status, statuses) ? 'x' : ' '
        yamlLines.push(`- [${check}] [[${basename}|${t.title}]]`)
      }
    }
    yamlLines.push('')
  }

  return yamlLines.join('\n')
}

export function buildTaskFrontmatter(task: Task, project: Project, parentTask: Task | null): Record<string, unknown> {
  const fm: Record<string, unknown> = {
    [TASK_FRONTMATTER_KEY]: true,
    projectId: project.id,
    parentId: parentTask?.id ?? null,
    id: task.id,
    title: task.title,
    type: task.type,
    status: task.status,
    priority: task.priority,
    start: task.start,
    due: task.due,
    progress: task.progress,
    assignees: task.assignees,
    tags: task.tags,
    subtaskIds: task.subtasks.map((s) => s.id),
    dependencies: task.dependencies,
    createdAt: task.createdAt,
    updatedAt: task.updatedAt
  }
  // Navigation links live here rather than in the body. The body IS the task's
  // description — it is what the Jira connector pushes to the issue — so nothing
  // generated may sit in it: a line we failed to strip back off leaks into Jira, and a
  // strip rule loose enough to always catch it eats the user's own text. As properties
  // they are still clickable in Obsidian, still counted as links, and unambiguous.
  const parentLink = parentTask?.filePath ? noteLink(parentTask.filePath, parentTask.title) : ''
  if (parentLink) fm.parent = parentLink
  else if (project.filePath) fm.project = noteLink(project.filePath, project.title)
  // Links for the children we hold in memory. `subtaskIds` stays the authoritative list
  // (it also carries preserved ids we have no title for) — these are for reading.
  if (task.subtasks.length) {
    fm.subtasks = task.subtasks.map((sub) => noteLink(sub.filePath || `${taskSlug(sub.title)}.md`, sub.title))
  }
  if (task.completed) fm.completed = task.completed
  if (task.recurrence) fm.recurrence = task.recurrence
  if (task.timeEstimate !== undefined) fm.timeEstimate = task.timeEstimate
  if (task.timeLogs?.length) fm.timeLogs = task.timeLogs
  if (Object.keys(task.customFields).length) fm.customFields = task.customFields
  if (task.ext) fm.ext = task.ext
  return fm
}

export function serializeTask(
  task: Task,
  project: Project,
  parentTask: Task | null,
  /** Child ids to keep in `subtaskIds` even though the in-memory task lost them —
   *  see ProjectStore.childIdsToPreserve. Prevents a stale write orphaning them. */
  preserveChildIds: string[] = []
): string {
  const fm = buildTaskFrontmatter(task, project, parentTask)
  if (preserveChildIds.length) {
    fm.subtaskIds = [...(fm.subtaskIds as string[]), ...preserveChildIds]
  }

  const yamlLines: string[] = ['---']
  appendYaml(yamlLines, fm, 0)
  yamlLines.push('---')
  yamlLines.push('')
  // Still stripped on the way out: a task loaded from a note written by an older version
  // carries the old generated block in its description until the note is rewritten.
  const cleanDesc = stripAutoGeneratedContent(task.description)
  if (cleanDesc) {
    yamlLines.push(cleanDesc)
    yamlLines.push('')
  }

  return yamlLines.join('\n')
}

/** `[[basename|Title]]` for a note path — the form Obsidian renders as a link. */
function noteLink(filePath: string, title: string): string {
  return `[[${filePath.replace(/^.*\//, '').replace(/\.md$/, '')}|${title}]]`
}

function taskSlug(title: string): string {
  return sanitizeFileName(title).toLowerCase().replace(/\s+/g, '-').slice(0, 40)
}

/** Build the file path for a task .md file */
export function taskFilePath(taskTitle: string, folder: string): string {
  return `${folder}/${taskSlug(taskTitle)}.md`
}
