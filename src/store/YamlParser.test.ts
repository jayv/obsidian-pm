import { describe, expect, it } from 'vitest'
import { appendYaml, isOldFormat, parseFrontmatter, stripAutoGeneratedContent } from './YamlParser'

describe('parseFrontmatter', () => {
  it('returns null frontmatter when the document has no fences', () => {
    const { frontmatter, body } = parseFrontmatter('just body text')
    expect(frontmatter).toBeNull()
    expect(body).toBe('just body text')
  })

  it('parses a fenced frontmatter block', () => {
    const doc = '---\ntitle: "Hello"\ncount: 3\n---\n\n# Body'
    const { frontmatter, body } = parseFrontmatter(doc)
    expect(frontmatter).toEqual({ title: 'Hello', count: 3 })
    expect(body).toBe('# Body')
  })

  it('returns the full content as body when the closing fence is missing', () => {
    const doc = '---\ntitle: "Hello"\n'
    const { frontmatter, body } = parseFrontmatter(doc)
    expect(frontmatter).toBeNull()
    expect(body).toBe(doc)
  })

  it('falls back to null on malformed yaml', () => {
    const doc = '---\n: : :\n---\nbody'
    const { frontmatter } = parseFrontmatter(doc)
    expect(frontmatter).toBeNull()
  })
})

/*
 * The body of a task note IS the task's description, and the Jira connector pushes it to
 * the issue. So this function has to be exact in both directions: leave a generated line
 * behind and it lands in Jira as text; take one line too many and the user's writing is
 * gone from the note AND from the issue.
 */
describe('stripAutoGeneratedContent', () => {
  it('removes a legacy Project wiki-link line', () => {
    expect(stripAutoGeneratedContent('Project: [[my-project|My Project]]')).toBe('')
  })

  it('removes a legacy Parent wiki-link line', () => {
    expect(stripAutoGeneratedContent('Parent: [[parent-slug|Parent]]')).toBe('')
  })

  it('removes the line even with trailing whitespace (the old rule missed it)', () => {
    // An editor that trims or re-wraps leaves a space; `$` then failed to match and the
    // wiki-link stayed in the description, from where it was pushed to Jira.
    expect(stripAutoGeneratedContent('Real text.\n\nParent: [[slug|Title]] ')).toBe('Real text.')
    expect(stripAutoGeneratedContent('Real text.\n\nParent: [[slug|Title]]\t')).toBe('Real text.')
  })

  it('removes the whole legacy block: nav line plus the Subtasks checklist', () => {
    const body = 'Description goes here\n\nParent: [[p|P]]\n\n## Subtasks\n- [ ] [[sub|Sub]]\n- [x] [[two|Two]]'
    expect(stripAutoGeneratedContent(body)).toBe('Description goes here')
  })

  it('removes a trailing Subtasks checklist on its own', () => {
    const body = 'Description goes here\n\n## Subtasks\n- [ ] [[sub|Sub]]'
    expect(stripAutoGeneratedContent(body)).toBe('Description goes here')
  })

  it("keeps a '## Subtasks' heading the user wrote themselves, and everything after it", () => {
    // The old rule deleted from the FIRST such heading to the end of the body, so this
    // note lost its Rollout section on the next save — and its Jira description with it.
    const body = 'Design notes.\n\n## Subtasks\n- split the parser\n\n## Rollout\nStaged behind a flag.'
    expect(stripAutoGeneratedContent(body)).toBe(body)
  })

  it('keeps a checklist that is not the generated shape', () => {
    const body = 'Notes.\n\n## Subtasks\n- [ ] write it up\n- [ ] [[link|Link]]'
    expect(stripAutoGeneratedContent(body)).toBe(body)
  })

  it('keeps user text written below the legacy block', () => {
    // The block was always written last, so anything after it is the user's. Leaving the
    // stale nav line in place is the cheaper mistake: it reads as a link, whereas the
    // greedy alternative deletes the paragraph.
    const body = 'Real text.\n\nParent: [[p|P]]\n\nA thought I typed underneath.'
    expect(stripAutoGeneratedContent(body)).toContain('A thought I typed underneath.')
  })

  it('preserves user content when no auto-generated markers exist', () => {
    expect(stripAutoGeneratedContent('Plain description.')).toBe('Plain description.')
  })
})

describe('isOldFormat', () => {
  it('is true when tasks is a non-empty array and taskIds is absent', () => {
    expect(isOldFormat({ tasks: [{ id: 'a' }] })).toBe(true)
  })

  it('is false when taskIds is present even if tasks is also set', () => {
    expect(isOldFormat({ tasks: [{ id: 'a' }], taskIds: ['a'] })).toBe(false)
  })

  it('is false when tasks is empty', () => {
    expect(isOldFormat({ tasks: [] })).toBe(false)
  })

  it('is false when tasks is absent', () => {
    expect(isOldFormat({ title: 'Project' })).toBe(false)
  })
})

describe('appendYaml', () => {
  it('serializes primitive types with quoted strings and unquoted numbers/bools', () => {
    const lines: string[] = []
    appendYaml(lines, { s: 'hi', n: 2, b: true, nil: null }, 0)
    expect(lines).toEqual(['s: "hi"', 'n: 2', 'b: true', 'nil:'])
  })

  it('escapes quotes, backslashes, and newlines in strings', () => {
    const lines: string[] = []
    appendYaml(lines, { s: 'a "b"\n\\c' }, 0)
    expect(lines).toEqual(['s: "a \\"b\\"\\n\\\\c"'])
  })

  it('emits inline arrays for primitive items and empty arrays as []', () => {
    const lines: string[] = []
    appendYaml(lines, { list: ['a', 'b'], empty: [] }, 0)
    expect(lines).toEqual(['list: ["a", "b"]', 'empty: []'])
  })

  it('emits nested blocks for arrays of objects', () => {
    const lines: string[] = []
    appendYaml(
      lines,
      {
        items: [
          { k: 'v1', n: 1 },
          { k: 'v2', n: 2 }
        ]
      },
      0
    )
    expect(lines).toEqual(['items:', '  - k: "v1"', '    n: 1', '  - k: "v2"', '    n: 2'])
  })

  it('indents nested objects by the given amount', () => {
    const lines: string[] = []
    appendYaml(lines, { outer: { inner: 'x' } }, 0)
    expect(lines).toEqual(['outer:', '  inner: "x"'])
  })
})
