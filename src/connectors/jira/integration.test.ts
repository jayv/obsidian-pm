import { TFile } from 'obsidian'
import type { App } from 'obsidian'
import { afterEach, describe, expect, it } from 'vitest'
import { makeFakeApp } from '../../../test/fakeVault'
import { FakeAdapter, must, mutateMock, setDefaultMaps } from './test-harness'
import { DEFAULT_PRIORITIES, DEFAULT_STATUSES, makeTask } from '../../types'
import type PMPlugin from '../../main'
import { ProjectStore } from '../../store/ProjectStore'
import { parseFrontmatter, stripAutoGeneratedContent } from '../../store/YamlParser'
import { findTask } from '../../store/TaskTreeOps'
import { stopMockServer } from './JiraMockServer'
import { ensureProjectCfg, taskExt } from './types'
import { exportTasks, fetchEpicStories, importStories, linkedKeys, runSync } from './sync'

/**
 * Drift guard: drive the JIRA connector through the REAL ProjectStore over the
 * in-memory vault (not the FakeStore). A behavioral change in the store —
 * saveProject no longer persisting fields, importTasks changing nesting, etc. —
 * fails here instead of silently breaking the plugin.
 */
describe('jira ↔ core store integration (real ProjectStore) [both]', () => {
  afterEach(() => stopMockServer())

  function realPlugin(team: string[] = []): { plugin: PMPlugin; store: ProjectStore; app: App } {
    const { app } = makeFakeApp()
    ;(app.vault as unknown as { adapter: FakeAdapter }).adapter = new FakeAdapter() // for jira-mock.json
    const settings = {
      projectsFolder: 'Projects',
      statuses: DEFAULT_STATUSES,
      priorities: DEFAULT_PRIORITIES,
      globalTeamMembers: team,
      connectors: { jira: { servers: [{ id: 's1', name: 'Local', site: 'localhost', email: 'x' }] } },
      connectorSecrets: {}
    }
    const store = new ProjectStore(app as unknown as App, () => settings.statuses)
    const plugin = {
      app,
      manifest: { dir: 'plugins/pm' },
      settings,
      store,
      refreshProjectViews() {},
      saveSettings: () => Promise.resolve()
    } as unknown as PMPlugin
    return { plugin, store, app: app as unknown as App }
  }

  async function connected(plugin: PMPlugin, store: ProjectStore, team: string[] = []) {
    const project = await store.createProject('Demo', 'Projects')
    project.teamMembers = team
    const cfg = ensureProjectCfg(project)
    cfg.enabled = true
    cfg.serverId = 's1'
    cfg.epicId = 'DEMO-100'
    setDefaultMaps(cfg)
    return { project, cfg }
  }

  const reload = async (store: ProjectStore, app: App, path: string) => {
    const file = app.vault.getAbstractFileByPath(path)
    if (!(file instanceof TFile)) throw new Error(`project file missing: ${path}`)
    return must(await store.loadProject(file), 'reloaded project')
  }

  it('export persists the linked JIRA key to the task .md (round-trips from disk)', async () => {
    const { plugin, store, app } = realPlugin()
    const { project } = await connected(plugin, store)
    const t = makeTask({ title: 'Build widget' })
    await store.insertTask(project, t, null)

    await exportTasks(plugin, project, [t.id])
    expect(taskExt(must(project.tasks.find((x) => x.title === 'Build widget'))).key).toBeTruthy()

    // Re-read from the vault: the key must have been persisted by the real store.
    const reloaded = await reload(store, app, project.filePath)
    const rt = must(reloaded.tasks.find((x) => x.title === 'Build widget'))
    expect(taskExt(rt).key).toBeTruthy()
    expect(taskExt(rt).sync).toBe(true)
  })

  /*
   * Live incident: after a structural change, one sync offered a pile of already-linked
   * issues for import. Nothing on disk was wrong before or after — the sync's in-memory
   * task tree was momentarily incomplete, and `newIssues` reads "no task claims this key"
   * as "this issue isn't tracked here". Importing then duplicates a task that exists.
   *
   * The tree is a snapshot; the vault is the durable answer. This drives the real store
   * with a task present on disk but absent from the tree — exactly that transient.
   */
  it('never offers an issue that a task file on disk already claims', async () => {
    const { plugin, store } = realPlugin()
    const { project } = await connected(plugin, store)
    const t = makeTask({ title: 'Already tracked' })
    await store.insertTask(project, t, null)
    await exportTasks(plugin, project, [t.id]) // linked, and persisted to its .md

    const key = must(taskExt(must(project.tasks.find((x) => x.title === 'Already tracked'))).key)
    // The tree loses the task; its note stays exactly where it was.
    project.tasks = project.tasks.filter((x) => x.title !== 'Already tracked')

    const r = await runSync(plugin, project)

    expect(r.newIssues.map((i) => i.key)).not.toContain(key)
    expect(await linkedKeys(plugin, project)).toContain(key) // the file still claims it
  })

  /*
   * ENG-14781: a link added in Jira was adopted into the note, then vanished, and the next
   * sync pushed the shortened description back — deleting it from the issue, with no
   * conflict raised. The write path trusted any body it had ever READ, and having read a
   * body is not the same as that copy still being current.
   *
   * These read the FILE, not the store's own objects: `loadProject` returns its cache, so
   * asserting through it can pass on memory alone while the note on disk says otherwise.
   */
  const bodyOnDisk = async (app: App, path: string | undefined): Promise<string> => {
    if (!path) throw new Error('task has no file path')
    const file = app.vault.getAbstractFileByPath(path)
    if (!(file instanceof TFile)) throw new Error(`no file at ${path}`)
    return stripAutoGeneratedContent(parseFrontmatter(await app.vault.cachedRead(file)).body)
  }

  it('writes an adopted description to the note, not the old body back over it', async () => {
    const { plugin, store, app } = realPlugin()
    const { project } = await connected(plugin, store)
    const t = makeTask({ title: 'Investigate', description: 'https://one.example' })
    await store.insertTask(project, t, null)

    // What the connector does when Jira is the side that changed.
    const both = 'https://one.example\n\nhttps://two.example'
    await store.applyExternalUpdates(project, [{ taskId: t.id, patch: { description: both } }])

    expect(await bodyOnDisk(app, must(findTask(project.tasks, t.id)).filePath)).toBe(both)
  })

  it('does not let a stale copy of a task overwrite a newer body', async () => {
    // Two Project objects for one vault is normal — a project tab, the all-projects view
    // and a pm-tasks panel each load their own, and a separate store is the only way to
    // get a genuinely separate copy (one store hands back its cache).
    const { plugin, store, app } = realPlugin()
    const { project } = await connected(plugin, store)
    const t = makeTask({ title: 'Investigate', description: 'https://one.example' })
    await store.insertTask(project, t, null)
    const path = must(must(findTask(project.tasks, t.id)).filePath, 'task file path')

    const other = new ProjectStore(app, () => plugin.settings.statuses)
    const otherView = must(
      await other.loadProject(must(app.vault.getAbstractFileByPath(path.replace(/_tasks\/.*$/, '.md')) as TFile | null))
    )
    const stale = must(findTask(otherView.tasks, t.id))
    await other.loadTaskBody(stale)
    expect(stale.description).toBe('https://one.example') // the copy is now behind

    const both = 'https://one.example\n\nhttps://two.example'
    await store.applyExternalUpdates(project, [{ taskId: t.id, patch: { description: both } }])

    // The stale view saves that task for an unrelated reason — a title edit, which forces
    // a full rewrite of the note. Its description is a read, not an edit, so the file has
    // to win. (A frontmatter-only change would never touch the body and can't show this.)
    await other.updateTask(otherView, stale.id, { title: 'Investigate Perfetto' })

    expect(await bodyOnDisk(app, must(findTask(otherView.tasks, t.id)).filePath)).toBe(both)
  })

  it('still writes a description the caller edited', async () => {
    // The other side of the rule: an authored body must reach disk, or every edit made in
    // the task modal would be read straight back off the file.
    const { plugin, store, app } = realPlugin()
    const { project } = await connected(plugin, store)
    const t = makeTask({ title: 'Investigate', description: 'before' })
    await store.insertTask(project, t, null)

    await store.updateTask(project, t.id, { description: 'after' })

    expect(await bodyOnDisk(app, must(findTask(project.tasks, t.id)).filePath)).toBe('after')
  })

  it('import persists nested subtasks and a new team member to disk', async () => {
    const { plugin, store, app } = realPlugin()
    const { project } = await connected(plugin, store)
    await runSync(plugin, project) // seed the local server + epic
    await mutateMock(plugin, (s) => {
      const story = s.createIssue({
        project: { key: 'DEMO' },
        issuetype: { name: 'Story' },
        summary: 'Story A',
        parent: { key: 'DEMO-100' }
      })
      s.createIssue({
        project: { key: 'DEMO' },
        issuetype: { name: 'Sub-task' },
        summary: 'Sub of A',
        parent: { key: story.key },
        assignee: { accountId: 'mock:carol', displayName: 'Carol' }
      })
    })

    const stories = await fetchEpicStories(plugin, project)
    await importStories(plugin, project, stories)

    const reloaded = await reload(store, app, project.filePath)
    const story = must(reloaded.tasks.find((x) => x.title === 'Story A'))
    expect(story.subtasks.map((s) => s.title)).toEqual(['Sub of A']) // hierarchy persisted
    expect(reloaded.teamMembers).toContain('Carol') // auto-created member persisted
  })
})
